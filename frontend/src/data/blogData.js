export const getBlogPostBySlug = (slug) => {
  if (!slug) return null;
  const cleanSlug = slug.toLowerCase()
    .replace(/^\/blog\//, '')
    .replace(/^\//, '')
    .replace(/\.htm$/, '')
    .trim();

  return blogPostsData.find(post => {
    const postSlugClean = post.slug.toLowerCase().replace(/\.htm$/, '');
    const postIdClean = post.id.toLowerCase();
    return (
      postSlugClean === cleanSlug ||
      postIdClean === cleanSlug ||
      cleanSlug.includes(postIdClean) ||
      postIdClean.includes(cleanSlug) ||
      cleanSlug.includes('41150') && post.slug.includes('41150') ||
      cleanSlug.includes('40190') && post.slug.includes('40190')
    );
  }) || blogPostsData[0];
};

// Function to dynamically get next N blogs excluding current blog for the "Explore More" sidebar
export const getExploreMoreBlogs = (currentPostId, count = 3) => {
  const otherPosts = blogPostsData.filter(post => post.id !== currentPostId);
  return otherPosts.slice(0, count);
};
